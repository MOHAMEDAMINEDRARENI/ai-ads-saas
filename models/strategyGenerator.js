const groq = require("../services/groq");

class StrategyGenerator {
    constructor(data) {
        this.data = data;
    }

    async generate() {

        const prompt = `
أنت مستشار تسويق رقمي عالمي بخبرة أكثر من 15 سنة في Facebook Ads و Instagram Ads، ومتخصص في السوق الجزائري.

مهمتك هي إنشاء تقرير احترافي بالكامل يساعد صاحب المشروع على إطلاق حملة إعلانية ناجحة وتحقيق أفضل النتائج.

بيانات المشروع:

- اسم المشروع: ${this.data.project_name}
- وصف المشروع: ${this.data.project_desc}
- الجمهور المستهدف: ${this.data.target_audience}
- الفئة العمرية: ${this.data.age_group}
- المنصة: ${this.data.platform}
- الميزانية اليومية: ${this.data.daily_budget} دولار
- مدة الحملة: ${this.data.campaign_days} يوم

أنشئ تقريرًا احترافيًا ومنظمًا جدًا يحتوي على:

1. تحليل الجمهور المستهدف بالتفصيل.

2. أفضل أنواع الإعلانات المناسبة:
- فيديو
- صورة
- Carousel
- Reels

3. أفكار محتوى احترافية.

4. مؤشرات الأداء المتوقعة (KPIs).

5. نصائح لتحسين ROAS.

6. استراتيجية Scaling.

7. أفضل أوقات النشر في الجزائر.

8. نص إعلاني احترافي جاهز للنشر على Facebook Ads و Instagram Ads.

9. Hook قوي يجذب الانتباه خلال أول 3 ثوانٍ.

10. Script كامل لفيديو إعلاني يحتوي على:
- ترتيب المشاهد.
- ماذا يقول المتحدث.
- طريقة جذب الزبون.
- Call To Action في النهاية.

11. Caption احترافي جاهز للنسخ.

12. CTA قوي يدفع العميل للشراء أو التواصل.

13. Hashtags مناسبة.

14. أفكار Creative للإعلانات.

15. Prompt احترافي باللغة الإنجليزية لإنشاء صورة إعلانية مناسب لـ:
- Midjourney
- Leonardo AI
- DALL·E

16. Prompt احترافي باللغة الإنجليزية لإنشاء فيديو AI مناسب لـ:
- Runway
- Pika
- Sora
- Kling AI

17. Style بصري مناسب للإعلان يشمل:
- الألوان
- نوع التصوير
- الإضاءة
- شكل المونتاج
- نوع الخطوط

18. أفكار Hooks بصرية للفيديو.

19. نصائح عملية لزيادة الأرباح وتشمل:
- زيادة معدل التحويل (Conversion Rate).
- تحسين ROAS.
- تقليل تكلفة الاكتساب (CPA).
- زيادة متوسط قيمة الطلب (Average Order Value).
- كيفية تحقيق أفضل عائد من الميزانية الإعلانية.

20. ملاحظات مهمة:
- أهم الأخطاء التي يجب تجنبها.
- ما الذي يجب مراقبته أثناء تشغيل الحملة.
- متى يتم إيقاف الحملة.
- متى يتم زيادة الميزانية.
- أهم النصائح قبل إطلاق الحملة وبعدها.

21. خطة Retargeting كاملة.

22. كيفية تقسيم الميزانية الإعلانية.

23. Checklist قبل إطلاق الحملة.

24. ملخص تنفيذي يحتوي على أهم التوصيات التي يجب تنفيذها أولاً.

=============================

تعليمات مهمة:

- استخدم عناوين رئيسية وعناوين فرعية واضحة.
- استخدم نقاطًا مرتبة.
- اجعل التقرير احترافيًا جدًا وسهل القراءة.
- لا تكرر المعلومات.
- لا تقدم نصائح عامة.
- خصص جميع الاقتراحات حسب بيانات المشروع المدخلة.
- ركز على السوق الجزائري.
- قدم حلولًا عملية قابلة للتطبيق.
- إذا كانت بعض المعلومات غير كافية، افترض أفضل سيناريو منطقي.
- اجعل التقرير يبدو وكأنه أعد بواسطة مستشار تسويق محترف وليس بواسطة ذكاء اصطناعي.
`;

        const response = await groq.chat.completions.create({
            model: "llama-3.3-70b-versatile",
            messages: [
                {
                    role: "user",
                    content: prompt
                }
            ],
            temperature: 0.7,
        });

        return {
            aiStrategy: response.choices[0].message.content
        };
    }
}

module.exports = StrategyGenerator;